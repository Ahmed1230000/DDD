<?php

namespace Ahmed\DDD\Core\ExecutionPlanBuilder;

final class ExecutionPlanBuilder
{
    public static function build(array $modules): array
    {
        $order = [

            /*
            |--------------------------------------------------------------------------
            | Persistence
            |--------------------------------------------------------------------------
            */

            // 'model',
            'migration',
            'factory',
            'seeder',

            /*
            |--------------------------------------------------------------------------
            | Domain
            |--------------------------------------------------------------------------
            */

            'entity',
            'repository_interface',
            'repository',
            'enum',
            'exception',

            /*
            |--------------------------------------------------------------------------
            | Application
            |--------------------------------------------------------------------------
            */

            'dto',
            'usecase',

            /*
            |--------------------------------------------------------------------------
            | Presentation
            |--------------------------------------------------------------------------
            */

            'request',
            'resource',
            'controller',

            /*
            |--------------------------------------------------------------------------
            | Infrastructure
            |--------------------------------------------------------------------------
            */

            'query_builder',

            /*
            |--------------------------------------------------------------------------
            | Security
            |--------------------------------------------------------------------------
            */

            'policy',

        ];

        return collect($modules)
            ->sortBy(
                fn($module) => array_search($module, $order)
            )
            ->values()
            ->toArray();
    }
}
